int text_width(const std::string& text, int scale) {
    if (text.empty()) return 0;
    int s = std::max(1, scale);
    return static_cast<int>(text.size()) * 6 * s;
}

int text_height(int scale) {
    int s = std::max(1, scale);
    return 7 * s;
}

void draw_text(Canvas& canvas, int x, int y, const std::string& text, Color color, int scale) {
    if (text.empty()) return;
    int s = std::max(1, scale);

    for (std::size_t i = 0; i < text.size(); ++i) {
        const std::uint8_t* glyph = lookup_glyph(text[i]);
        int char_x = x + static_cast<int>(i) * 6 * s;

        for (int r = 0; r < 7; ++r) {
            std::uint8_t row_byte = glyph[r];
            for (int c = 0; c < 5; ++c) {
                if ((row_byte >> (4 - c)) & 1) {
                    for (int dy = 0; dy < s; ++dy) {
                        for (int dx = 0; dx < s; ++dx) {
                            canvas.set_pixel(char_x + c * s + dx, y + r * s + dy, color);
                        }
                    }
                }
            }
        }
    }
}

void draw_text_vertical(Canvas& canvas, int x, int y, const std::string& text, Color color, int scale) {
    if (text.empty()) return;
    int s = std::max(1, scale);
    int n = static_cast<int>(text.size());

    for (int i = 0; i < n; ++i) {
        const std::uint8_t* glyph = lookup_glyph(text[static_cast<std::size_t>(i)]);
        int char_y = y + (n - 1 - i) * 6 * s;

        for (int r = 0; r < 7; ++r) {
            std::uint8_t row_byte = glyph[r];
            for (int c = 0; c < 5; ++c) {
                if ((row_byte >> (4 - c)) & 1) {
                    for (int dy = 0; dy < s; ++dy) {
                        for (int dx = 0; dx < s; ++dx) {
                            int px = x + r * s + dx;
                            int py = char_y + (5 - c) * s - 1 - dy;
                            canvas.set_pixel(px, py, color);
                        }
                    }
                }
            }
        }
    }
}

